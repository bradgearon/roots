#include "llama.h"
#include "ggml-backend.h"
#include <algorithm>
#include <cmath>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <memory>
#include <stdexcept>
#include <string>
#include <vector>

static std::vector<llama_token> tokenize(const llama_vocab *v, const std::string &s) {
    std::vector<llama_token> t(s.size()+32);
    int n=llama_tokenize(v,s.data(),static_cast<int>(s.size()),t.data(),static_cast<int>(t.size()),true,true);
    if(n<0){ t.resize(-n); n=llama_tokenize(v,s.data(),static_cast<int>(s.size()),t.data(),static_cast<int>(t.size()),true,true); }
    if(n<=0) throw std::runtime_error("tokenization failed");
    t.resize(n); return t;
}
int main(int argc, char **argv) {
    if(argc!=6){std::cerr<<"atlas-score MODEL TASKS.tsv base|it THREADS GPU_LAYERS\n"; return 2;}
    try {
        std::string mode=argv[3];
        if(mode!="base" && mode!="it") throw std::runtime_error("invalid prompt mode");
        const int threads=std::stoi(argv[4]), gpu=std::stoi(argv[5]);
        if(threads<1 || gpu<0) throw std::runtime_error("invalid device settings");
        ggml_backend_load_all();
        llama_backend_init();
        auto mp=llama_model_default_params(); mp.n_gpu_layers=gpu;
        std::unique_ptr<llama_model,decltype(&llama_model_free)> model(llama_model_load_from_file(argv[1],mp),llama_model_free);
        if(!model) throw std::runtime_error("model load failed");
        auto cp=llama_context_default_params(); cp.n_ctx=512; cp.n_batch=512; cp.n_ubatch=512;
        cp.n_threads=threads; cp.n_threads_batch=threads;
        std::unique_ptr<llama_context,decltype(&llama_free)> ctx(llama_init_from_model(model.get(),cp),llama_free);
        if(!ctx) throw std::runtime_error("context init failed");
        const auto *v=llama_model_get_vocab(model.get());
        std::ifstream in(argv[2],std::ios::binary);
        if(!in) throw std::runtime_error("cannot read task file");
        std::string line;
        std::cout<<std::setprecision(10);
        while(std::getline(in,line)){
            if(!line.empty() && line.back()=='\r') line.pop_back();
            auto tab=line.find('\t'); if(tab==std::string::npos) throw std::runtime_error("bad task row");
            auto id=line.substr(0,tab), question=line.substr(tab+1);
            // Newlines are encoded as ASCII | in the TSV generated by atlas.py.
            std::replace(question.begin(),question.end(),'|','\n');
            std::string prompt=mode=="it" ? "<start_of_turn>user\n"+question+"<end_of_turn>\n<start_of_turn>model\n" : question+"\nAnswer:";
            auto a=tokenize(v,prompt+(mode=="it"?"A":" A"));
            auto b=tokenize(v,prompt+(mode=="it"?"B":" B"));
            size_t n=0;
            while(n<a.size() && n<b.size() && a[n]==b[n]) ++n;
            // Exact logit comparison requires a shared prefix and a single distinct final token.
            if(n==0 || n+1!=a.size() || n+1!=b.size() || n>=512)
                throw std::runtime_error("A/B not single-token continuations for "+id+"; inspect tokenizer/template");
            llama_memory_clear(llama_get_memory(ctx.get()),true);
            if(llama_decode(ctx.get(),llama_batch_get_one(a.data(),static_cast<int>(n)))!=0)
                throw std::runtime_error("decode failed: "+id);
            auto *logits=llama_get_logits_ith(ctx.get(),-1);
            if(!logits) throw std::runtime_error("missing logits");
            double margin=double(logits[a[n]])-double(logits[b[n]]);
            if(!std::isfinite(margin)) throw std::runtime_error("non-finite logit margin");
            std::cout<<id<<'\t'<<margin<<'\n';
        }
        ctx.reset(); model.reset(); llama_backend_free();
    } catch(const std::exception &e){std::cerr<<"atlas-score: "<<e.what()<<'\n';return 1;}
}
